CREATE TABLE publication_tonawanda_tension_cell (
    source_id TEXT NOT NULL REFERENCES publication_source,
    cell_key TEXT NOT NULL,
    source_table TEXT NOT NULL CHECK(source_table IN ('I','II')),
    source_section TEXT CHECK(source_section IN ('A','B','C','D','E')),
    analysis INTEGER NOT NULL CHECK(analysis IN (10,12,13,14,15)),
    pressure_lower_mmhg INTEGER NOT NULL CHECK(pressure_lower_mmhg > 0),
    pressure_upper_mmhg INTEGER NOT NULL CHECK(pressure_upper_mmhg > pressure_lower_mmhg),
    nitrogen_lower_mmhg INTEGER CHECK(nitrogen_lower_mmhg >= 0),
    nitrogen_upper_mmhg INTEGER CHECK(nitrogen_upper_mmhg >= coalesce(nitrogen_lower_mmhg,0)),
    minimum_residence_exclusive_min INTEGER CHECK(minimum_residence_exclusive_min IN (15,30)),
    reported_grade_label TEXT NOT NULL,
    qualifying_maximum_grade_min INTEGER CHECK(qualifying_maximum_grade_min IN (3,4)),
    first_hit_grade_min INTEGER CHECK(first_hit_grade_min IN (2,3)),
    reported_events INTEGER NOT NULL CHECK(reported_events BETWEEN 0 AND reported_records),
    reported_records INTEGER NOT NULL CHECK(reported_records >= 0),
    cumulative_records INTEGER CHECK(cumulative_records >= reported_records),
    reported_percent INTEGER CHECK(reported_percent BETWEEN 0 AND 100),
    rate_discrepancy INTEGER NOT NULL CHECK(rate_discrepancy IN (0,1)),
    row_status TEXT NOT NULL CHECK(row_status IN ('observation','table_i_prefix','original_prefix','no_flights')),
    reference_cells_json TEXT NOT NULL CHECK(json_type(reference_cells_json) = 'array'),
    observation_stratum TEXT,
    observation_endpoint TEXT,
    locator TEXT NOT NULL,
    note TEXT NOT NULL,
    PRIMARY KEY(source_id,cell_key),
    UNIQUE(source_id,observation_stratum,observation_endpoint),
    FOREIGN KEY(source_id,observation_stratum,observation_endpoint)
        REFERENCES publication_observation(source_id,stratum,endpoint),
    CHECK((source_table = 'II') = (source_section IS NOT NULL)),
    CHECK((source_table = 'II') = (reported_percent IS NOT NULL)),
    CHECK((row_status = 'no_flights') = (reported_records = 0)),
    CHECK((row_status = 'observation') = (observation_stratum IS NOT NULL)),
    CHECK((observation_stratum IS NULL) = (observation_endpoint IS NULL)),
    CHECK((row_status IN ('table_i_prefix','original_prefix')) = (json_array_length(reference_cells_json) > 0))
) STRICT;
